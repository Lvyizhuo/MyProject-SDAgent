-- ============================================================
-- V1: 核心基础表（此前由 Hibernate ddl-auto 自动创建，无 Flyway 脚本）
-- 涉及：users / knowledge_config / knowledge_folders / knowledge_documents
-- 必须排在 V2 之前：V4 的 url_import 表会外键引用 knowledge_folders / knowledge_documents
-- 表结构对齐 Hibernate 6.6 实体的最终形态；V6/V7 的 ADD COLUMN 用 IF NOT EXISTS，会自动跳过
-- 配合 ddl-auto=validate 使用
-- ============================================================

-- 1. 用户表
CREATE TABLE IF NOT EXISTS users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(255) NOT NULL CHECK (role IN ('USER','ADMIN')),
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

-- 2. 知识库全局配置表（单行，固定 id=1）
CREATE TABLE IF NOT EXISTS knowledge_config (
    id                      BIGINT NOT NULL,
    chunk_size              INTEGER,
    chunk_overlap           INTEGER,
    min_chunk_size_chars    INTEGER,
    no_split_max_chars      INTEGER,
    default_embedding_model VARCHAR(200),
    minio_endpoint          VARCHAR(500),
    minio_access_key        VARCHAR(200),
    minio_secret_key        VARCHAR(200),
    minio_bucket_name       VARCHAR(100),
    created_at              TIMESTAMP(6) NOT NULL,
    updated_at              TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

-- 3. 知识文件夹（目录树，自引用）
CREATE TABLE IF NOT EXISTS knowledge_folders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    parent_id         BIGINT,
    name              VARCHAR(200) NOT NULL,
    description       TEXT,
    path              VARCHAR(500) NOT NULL UNIQUE,
    depth             INTEGER NOT NULL,
    sort_order        INTEGER,
    embedding_model   VARCHAR(200) NOT NULL,
    vector_table_name VARCHAR(100) NOT NULL,
    rerank_model_id   BIGINT,
    rerank_model_name VARCHAR(200),
    init_status       VARCHAR(32),
    init_error        TEXT,
    initialized_at    TIMESTAMP(6),
    created_at        TIMESTAMP(6) NOT NULL,
    created_by        BIGINT,
    updated_at        TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

-- 4. 知识文档（fileName/fileSize/fileType 与实体字段名保持一致）
CREATE TABLE IF NOT EXISTS knowledge_documents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    folder_id         BIGINT,
    title             VARCHAR(500) NOT NULL,
    fileName          VARCHAR(500) NOT NULL,
    fileSize          BIGINT NOT NULL,
    fileType          VARCHAR(100) NOT NULL,
    storage_path      VARCHAR(1000) NOT NULL,
    storage_bucket    VARCHAR(100) NOT NULL,
    embedding_model   VARCHAR(200) NOT NULL,
    vector_table_name VARCHAR(100) NOT NULL,
    category          VARCHAR(200),
    tags              VARCHAR(500)[],
    publish_date      DATE,
    source            VARCHAR(500),
    valid_from        DATE,
    valid_to          DATE,
    summary           TEXT,
    status            VARCHAR(50) NOT NULL CHECK (status IN ('PENDING','PROCESSING','COMPLETED','FAILED')),
    error_message     TEXT,
    chunk_count       INTEGER,
    created_at        TIMESTAMP(6) NOT NULL,
    created_by        BIGINT,
    updated_at        TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

-- 5. 外键约束（幂等，避免重复创建报错）
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_knowledge_folders_parent') THEN
        ALTER TABLE knowledge_folders ADD CONSTRAINT fk_knowledge_folders_parent
            FOREIGN KEY (parent_id) REFERENCES knowledge_folders(id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_knowledge_folders_created_by') THEN
        ALTER TABLE knowledge_folders ADD CONSTRAINT fk_knowledge_folders_created_by
            FOREIGN KEY (created_by) REFERENCES users(id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_knowledge_documents_folder') THEN
        ALTER TABLE knowledge_documents ADD CONSTRAINT fk_knowledge_documents_folder
            FOREIGN KEY (folder_id) REFERENCES knowledge_folders(id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_knowledge_documents_created_by') THEN
        ALTER TABLE knowledge_documents ADD CONSTRAINT fk_knowledge_documents_created_by
            FOREIGN KEY (created_by) REFERENCES users(id);
    END IF;
END $$;
